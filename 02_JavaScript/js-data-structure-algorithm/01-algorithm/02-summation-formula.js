// ตัวอย่างที่ 2: หาผลรวม 1 + 2 + ... + n ด้วยสูตรคณิตศาสตร์
// เปรียบเทียบกับ 01-summation-loop.js : ผลลัพธ์เท่ากัน แต่เร็วกว่ามาก
// =====================================================

function summation(n) {
  // สูตรผลรวมอนุกรม n(n+1)/2 คำนวณครั้งเดียวไม่ต้องวนลูป
  return (n * (n + 1)) / 2;
}

const n = 300_000_000; // สามร้อยล้าน

console.time("summation (formula)");
summation(n);
console.timeEnd("summation (formula)");
