// ตัวอย่างที่ 1: หาผลรวม 1 + 2 + 3 + ... + n ด้วยลูป
// บทเรียน: การวัดประสิทธิภาพอัลกอริทึม / เขียนโปรแกรมจับเวลา
// =====================================================

function summation(n) {
  let total = 0; // ตัวแปรเก็บผลรวม
  for (let i = 1; i <= n; i++) {
    total += i; // บวกเลขทีละตัว จึงทำงานทั้งหมด n รอบ
  }
  return total;
}

const n = 300_000_000; // สามร้อยล้าน

console.time("summation (loop)"); // เริ่มจับเวลา
summation(n);
console.timeEnd("summation (loop)"); // หยุดจับเวลาและแสดงผล
