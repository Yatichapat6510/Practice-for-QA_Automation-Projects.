// =====================================================
// Constant Time : O(1)
// ใช้เวลาเท่าเดิมเสมอ ไม่ว่าข้อมูลจะมีกี่ตัว
// =====================================================

function firstElement(array) {
  return array[0]; // เข้าถึงตำแหน่งที่ 0 ได้ทันที = O(1)
}

const score = [70, 30, 15, 90, 50];
console.log(firstElement(score)); // 70
