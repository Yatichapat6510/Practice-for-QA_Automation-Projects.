// =====================================================
// Exponential Time : O(2^n)
// ตัวอย่าง: ฟีโบนัชชีแบบเรียกตัวเอง (Recursion)
// แต่ละครั้งแตกออกเป็น 2 การเรียก จำนวนครั้งโตเป็นเท่าตัว
// =====================================================

function fibonacci(n) {
  if (n <= 1) {
    return n; // เงื่อนไขหยุดการเรียกตัวเอง (Base case)
  }
  return fibonacci(n - 2) + fibonacci(n - 1);
}

console.log(fibonacci(6)); // 8
// ลองเพิ่มเป็น fibonacci(40) จะเห็นว่าช้าลงมาก
