# เขียนโปรแกรมหาเลข มาก / น้อย
#ค้าง as 1 / 4/ 5/ 6/ 7/ 8/ ค่อยดูต่อ

a = int(input("ป้อนตัวเลขที่ 1 : "))  
b = int(input("ป้อนตัวเลขที่ 2 : "))

if a > b :
    print(a,"มากกว่า",b)
else : 
    print(a,"น้อยกว่า",b)

# เลขคู่ / คี่
    
number = int(input("ป้อนเลขของคุณ : "))

#ถ้าหาร 2 ลงตัว => คู่

if number % 2 == 0:
    print("เป็นเลขคู่")
else : 
    print("เป็นเลขคี่")
    
